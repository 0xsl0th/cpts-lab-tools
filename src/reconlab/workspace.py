"""Workspace management - lab folder layout, metadata persistence, scan discovery."""

from __future__ import annotations

import json
import tarfile
from dataclasses import asdict, dataclass, field, fields
from datetime import datetime, timezone
from pathlib import Path

from . import nmap as _nmap

METADATA_FILENAME = ".reconlab.json"
WORKSPACE_FOLDERS: tuple[str, ...] = (
    "scans",
    "screenshots",
    "loot",
    "notes",
    "exploits",
    "creds",
    "web",
)
SCAN_EXTENSIONS: tuple[str, ...] = (".xml", ".nmap", ".gnmap")
WEB_EXTENSIONS: tuple[str, ...] = (".txt", ".json")


@dataclass
class WorkspaceMetadata:
    name: str
    target_ip: str | None = None
    target_host: str | None = None
    domain: str | None = None
    platform: str = "lab"
    status: str = "in-progress"
    created_at: str = ""

    @classmethod
    def from_dict(cls, data: dict) -> "WorkspaceMetadata":
        known = {f.name for f in fields(cls)}
        return cls(**{k: v for k, v in data.items() if k in known})

    def to_dict(self) -> dict:
        return asdict(self)


def metadata_path(workspace: Path) -> Path:
    return workspace / METADATA_FILENAME


def read_metadata(workspace: Path) -> WorkspaceMetadata:
    path = metadata_path(workspace)
    if not path.is_file():
        raise FileNotFoundError(
            f"No workspace metadata at {path}. "
            "Run `reconlab workspace init <name>` first."
        )
    data = json.loads(path.read_text(encoding="utf-8"))
    return WorkspaceMetadata.from_dict(data)


def write_metadata(workspace: Path, metadata: WorkspaceMetadata) -> None:
    metadata_path(workspace).write_text(
        json.dumps(metadata.to_dict(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def _utc_now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


